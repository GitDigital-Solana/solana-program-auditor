import type { GhClient } from './client';
import type { AuditResult, Finding, Severity } from '../auditor/engine';

const MARKER = '<!-- solana-program-auditor -->';

const SEVERITY_ICON: Record<Severity, string> = {
  critical: '🔴',
  high: '🟠',
  medium: '🟡',
  low: '🔵'
};

const SEVERITY_ORDER: Record<Severity, number> = {
  critical: 0,
  high: 1,
  medium: 2,
  low: 3
};

function escapeCell(s: string): string {
  return s.replace(/\|/g, '\\|').replace(/\n/g, ' ');
}

function sortFindings(findings: Finding[]): Finding[] {
  return [...findings].sort((a, b) => {
    const s = SEVERITY_ORDER[a.severity] - SEVERITY_ORDER[b.severity];
    if (s !== 0) return s;
    if (a.file !== b.file) return a.file.localeCompare(b.file);
    return a.line - b.line;
  });
}

export function renderComment(result: AuditResult): string {
  const lines: string[] = [];
  const { summary } = result;

  lines.push('## 🔒 Solana Program Auditor');
  lines.push('');
  if (summary.total === 0) {
    lines.push('✅ **No findings** — this PR passed all configured checks.');
  } else {
    const parts = [
      `${summary.critical} critical`,
      `${summary.high} high`,
      `${summary.medium} medium`,
      `${summary.low} low`
    ].filter((p) => !p.startsWith('0 '));
    lines.push(`**${summary.total} findings** (${parts.join(', ')}) in ${result.durationMs}ms`);
    lines.push('');
    lines.push('| Severity | Rule | File | Line | Message |');
    lines.push('| --- | --- | --- | --- | --- |');
    for (const f of sortFindings(result.findings).slice(0, 200)) {
      lines.push(
        `| ${SEVERITY_ICON[f.severity]} ${f.severity} | \`${f.ruleId}\` | \`${escapeCell(f.file)}\` | ${f.line} | ${escapeCell(f.message)} |`
      );
    }
    if (result.findings.length > 200) {
      lines.push(`| … | | | | +${result.findings.length - 200} more (truncated) |`);
    }
  }

  if (result.dynamic.ran) {
    lines.push('');
    lines.push(
      result.dynamic.passed ? '🧪 Dynamic tests: **passed**' : '🧪 Dynamic tests: **failed**'
    );
  }

  lines.push('');
  lines.push('<sub>Generated by solana-program-auditor</sub>');
  return lines.join('\n');
}

async function findExisting(
  client: GhClient,
  owner: string,
  repo: string,
  prNumber: number
): Promise<{ id: number } | undefined> {
  const comments = await client.paginate(client.issues.listComments, {
    owner,
    repo,
    issue_number: prNumber,
    per_page: 100
  });
  return comments.find((c) => c.body?.startsWith(MARKER));
}

export async function postOrUpdateComment(
  client: GhClient,
  owner: string,
  repo: string,
  prNumber: number,
  body: string,
  updateExisting = true
): Promise<void> {
  const full = `${MARKER}\n${body}`;
  const existing = updateExisting
    ? await findExisting(client, owner, repo, prNumber)
    : undefined;
  if (existing) {
    await client.issues.updateComment({
      owner,
      repo,
      comment_id: existing.id,
      body: full
    });
  } else {
    await client.issues.createComment({
      owner,
      repo,
      issue_number: prNumber,
      body: full
    });
  }
}